  <p class="eyebrow">مصادر المحتوى</p>
  <h1>منهج كامل.<br />وتعلّم بالعربية.</h1>
  <p>
    موقع تعليمي مستقل يعتمد على <a href="https://web.dev/learn/?hl=ar"
      >منهج web.dev</a
    >، بما فيه كورس الذكاء الاصطناعي. ليس منتجًا رسميًا من Google أو web.dev.
  </p>
  <h2>الترجمة ونسب المحتوى</h2>
  <p>
    نعرض النسخة العربية المتاحة من المصدر، والتي قد تتضمن ترجمة آلية. نحافظ على
    أمثلة الأكواد والمصطلحات البرمجية، ونضيف تمارين تذكّر مستخرجة من النص،
    واختبارات تفاعلية وحفظ التقدم. يمكنك الرجوع إلى رابط المصدر في كل درس.
  </p>
  <p>
    النصوص والوسائط مرخّصة بموجب <a
      href="https://creativecommons.org/licenses/by/4.0/deed.ar"
      >نَسب المُصنَّف 4.0 من المشاع الإبداعي</a
    >، ما لم يُذكر غير ذلك. أمثلة الأكواد تخضع إلى
    <a href="https://www.apache.org/licenses/LICENSE-2.0">ترخيص Apache 2.0</a>.
    نحتفظ بأسماء المؤلفين وروابط المصدر وبيانات التحديث حيث تتوفر. الأمثلة
    الخارجية لها شروطها الخاصة.
  </p>
  <h2>متى يُحتسب الدرس مكتملًا؟</h2>
  <p>
    نسبة التقدم هي عدد الدروس المنشورة المكتملة مقسومًا على إجمالي الدروس
    المنشورة. لا تُحتسب الصفحات غير المتاحة أو التي ستُنشر لاحقًا. الدروس ذات
    الأسئلة المعتمدة تحتاج إلى إجابات صحيحة قبل الإكمال؛ أما دروس القراءة فيمكن
    إكمالها بعد الدراسة. يظل سجل الإكمال محفوظًا عند تحديث المنهج.
  </p>
  <h2>ترتيب المنهج وتحديثاته</h2>
  <p>
    نحافظ على ترتيب الدروس الأصلي داخل كل كورس. يبدأ المسار المقترح بـ HTML
    وCSS، ثم التصميم المتجاوب، وJavaScript، والنماذج، وإمكانية الوصول، والصور،
    والأداء، والخصوصية، وتطبيقات الويب التقدمية، والاختبار، ثم الذكاء الاصطناعي.
    تُراجع الكورسات الجديدة لتحديد موضعها في المسار.
  </p>
  <h2>بياناتك</h2>
  <p>
    نسجّل معرّف حساب GitHub واسم العرض عند تسجيل الدخول. تشمل بيانات التعلّم
    الإجابات ومكان القراءة والإكمال وسجل المراجعة. لا نخزّن رموز وصول GitHub،
    وتقدّمك خاص بحسابك.
  </p>
